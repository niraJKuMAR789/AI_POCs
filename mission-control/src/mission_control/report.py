"""Markdown report for a drill (committed to the repo as evidence)."""

from __future__ import annotations

from collections import Counter
from typing import Any

from mission_control.drill import WINDOW_MIN, DrillResult, kpis


def _mark(ok: bool) -> str:
    return "✅" if ok else "❌"


def _fmt_pair(pair: tuple[Any, Any], unit: str = "", pct: bool = False) -> str:
    a, b = pair
    if pct:
        return f"{a:.0%} → **{b:.0%}**"
    return f"{a}{unit} → **{b}{unit}**"


def render(results: list[DrillResult]) -> str:
    main = results[0]
    cfg, sc = main.config, main.scenario
    lines = [
        "# Mission Control: fault drill report",
        "",
        f"Provider: `{cfg.provider}` · virtual duration: {sc.minutes} min · detection window: {WINDOW_MIN} min · "
        f"RCA: `{'LLM investigator' if cfg.llm_rca else 'deterministic'}` · seeds: "
        f"{', '.join(str(r.config.seed) for r in results)}",
        "",
        "Atlas, Quill and Aegis serve real requests and export traces to one Argus org. Three faults are injected",
        "below the instrumentation; Argus is not told about them. Generated by `mission-control drill`.",
        "",
    ]
    if len(results) > 1:
        lines += [
            "## Summary across seeds",
            "",
            "| seed | requests | detected | root cause correct | median delay | false alarms | wall time |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in results:
            delays = sorted(s.delay_min for s in r.scores if s.delay_min is not None)
            lines.append(
                f"| {r.config.seed} | {len(r.requests):,} | {sum(s.detected for s in r.scores)}/{len(r.scores)} | "
                f"{sum(s.rca_correct for s in r.scores)}/{len(r.scores)} | "
                f"{delays[len(delays) // 2] if delays else '-'} min | {len(r.false_alarms)} | {r.wall_s:.0f} s |"
            )
        lines.append("")

    lines += [
        f"## Seed {cfg.seed} in detail",
        "",
        "### Timeline",
        "",
        "| minute | app | event |",
        "|---|---|---|",
    ]
    events = [(c.minute, c.app, f"{c.kind}: {c.description}") for c in sc.changes]
    events += [(f.start_min, f.app, f"**fault {f.id} starts** (hidden from Argus): {f.description}") for f in sc.faults]
    events += [(f.end_min, f.app, f"fault {f.id} ends") for f in sc.faults]
    for minute, app, text in sorted(events, key=lambda e: (e[0], e[2])):
        lines.append(f"| {minute:g} | {app} | {text} |")

    lines += [
        "",
        "### Did Argus catch it, and explain it?",
        "",
        "| fault | app | detected | delay | Argus's root cause | expected | correct |",
        "|---|---|---|---|---|---|---|",
    ]
    for s in main.scores:
        rca = s.rca or {}
        found = f"{rca.get('category', '-')} · `{rca.get('cause_dimension', '')}={rca.get('cause_value', '')}`"
        lines.append(
            f"| {s.fault.id} {s.fault.title} | {s.fault.app} | {_mark(s.detected)} | "
            f"{'-' if s.delay_min is None else f'{s.delay_min:g} min'} | {found if s.rca else '-'} | "
            f"{s.fault.expected_category} · `{s.fault.cause_dimension}={s.fault.cause_value}` | "
            f"{_mark(s.rca_correct)} |"
        )
    lines += ["", "Delay is measured from fault start to the end of the first window that raised an anomaly.", ""]

    impact = kpis(main)
    lines += ["### What the business would have seen", "", "| fault | metric | before → during |", "|---|---|---|"]
    names = {
        "p50_latency_ms": ("p50 request latency", " ms", False),
        "avg_sql_attempts": ("SQL attempts per question", "", False),
        "sent_to_human_review": ("claims sent to human review", "", True),
    }
    for fid, entry in impact.items():
        for key, (label, unit, pct) in names.items():
            if key in entry:
                lines.append(f"| {fid} | {label} | {_fmt_pair(entry[key], unit, pct)} |")
    lines.append("")

    lines += ["### Investigations", ""]
    for s in main.scores:
        if not s.rca:
            continue
        rca = s.rca
        lines += [f"**{s.fault.id} → incident #{rca['incident']}.** {rca.get('summary', '')}", ""]
        for ev in rca.get("evidence", [])[:6]:
            lines.append(f"- `{ev['kind']}` {ev['ref']}: {ev.get('detail', '')}")
        actions = "; ".join(rca.get("recommended_actions", []))
        lines += ["", f"Recommended: {actions}." if actions else "", ""]

    lines += ["### False alarms", ""]
    if main.false_alarms:
        for inc in main.false_alarms:
            app = next(a for a, pid in main.projects.items() if pid == inc.project_id)
            lines.append(f"- {app}: {inc.title} ({inc.severity}, detectors: {', '.join(inc.detectors)})")
    else:
        lines.append("None: every incident Argus opened maps to an injected fault.")
    lines.append("")

    lines += [
        "### Governance (same run)",
        "",
        "| app | traces | spans | spans with PII (redacted or blocked) | policy violations |",
        "|---|---|---|---|---|",
    ]
    store = main.argus.store
    for app, pid in main.projects.items():
        t = store.query(
            "SELECT COUNT(*) AS n, COALESCE(SUM(span_count), 0) AS spans, COALESCE(SUM(pii_spans), 0) AS pii "
            "FROM traces WHERE project_id = ?",
            (pid,),
        )[0]
        counts = Counter(v.policy for v in store.violations(pid, limit=100000))
        summary = ", ".join(f"{k}: {n:,}" for k, n in counts.most_common()) or "none"
        lines.append(f"| {app} | {t['n']:,} | {t['spans']:,} | {t['pii']:,} | {summary} |")
    lines += [
        "",
        "Policies: [`config/policies.yaml`](../config/policies.yaml). Quill's `step_limit` violations are the",
        "prompt regression's repair loop showing up in governance as well as in detection.",
        "",
    ]
    return "\n".join(lines)
